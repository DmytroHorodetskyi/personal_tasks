zin = zipfile.ZipFile(src)
x = zin.read("word/document.xml").decode("utf-8")

paras = list(re.finditer(r"<w:p[ >].*?</w:p>", x, re.S))
assert len(paras) == 67, len(paras)


def rebuild(p_xml, text):
    ppr = re.search(r"<w:pPr>.*?</w:pPr>", p_xml, re.S)
    ppr = ppr.group(0) if ppr else ""
    rpr = re.search(r"<w:r[ >].*?(<w:rPr>.*?</w:rPr>)", p_xml, re.S)
    rpr = rpr.group(1) if rpr else ""
    open_tag = re.match(r"<w:p[^>]*>", p_xml).group(0)
    runs = ""
    if text:
        for i, part in enumerate(text.split("\n")):
            if i:
                runs += "<w:r>%s<w:br/></w:r>" % rpr
            runs += '<w:r>%s<w:t xml:space="preserve">%s</w:t></w:r>' % (rpr, escape(part))
    return open_tag + ppr + runs + "</w:p>"


out, last = [], 0
for i, m in enumerate(paras):
    if i in NEW:
        out.append(x[last:m.start()])
        out.append(rebuild(m.group(0), NEW[i]))
        last = m.end()
new_x = "".join(out) + x[last:]
